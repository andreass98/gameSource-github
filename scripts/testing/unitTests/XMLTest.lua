function XMLTest.test_setXMLInt()
    local xml = createXMLFile("XMLTest", "", "test")
    setXMLInt(xml, "test.int", 2147483647)
    Assert.areEqual(getXMLString(xml, "test.int"), (tostring(2147483647)))
    setXMLInt(xml, "test.int", -2147483648)
    Assert.areEqual(getXMLString(xml, "test.int"), (tostring(-2147483648)))
    setXMLInt(xml, "test.int", 1.8)
    Assert.areEqual(getXMLString(xml, "test.int"), (tostring(2)))
