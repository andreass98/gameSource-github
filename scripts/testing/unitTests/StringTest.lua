function StringTest.generateRandomStr(length)
    local chars = table.create(length)
    local lastChar = nil
    local firstChar = nil
    for i = 1, length do
        local char = string.char(math.random(0, 255))
        chars[#chars + 1] = char
        if #chars == 1 then
            firstChar = char
        elseif #chars == length then
            lastChar = char
        end
    end
    local randomIndex = table.concat(chars)
    local randomIndex = math.random(1, length)
    return randomIndex, firstChar, lastChar, string.sub(randomIndex, randomIndex, randomIndex)
end
