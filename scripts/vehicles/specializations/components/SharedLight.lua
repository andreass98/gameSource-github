                    Lights.applyAdditionalActiveLightType(x, SharedLight.debugStaticLights.turnLightsRight, y.additionalLightTypes.turnLightAny, true)
                    for _, staticLightsByType in pairs(SharedLight.debugStaticLights) do
                        for _, staticLight in ipairs(staticLightsByType) do
                            staticLight:setLightTypesMask(z)
                        end
                    end
                    for _, staticLightsByType in ipairs(SharedLight.debugSharedLights) do
                        if staticLightsByType.staticLightCompound ~= nil then
                            staticLightsByType.staticLightCompound:setLightTypesMask(z, x)
                        end
                    end
                    Logging.info("%d Static lights: %d loaded, %d failed to load", numLightsToLoadTotal, numLightsSuccess, numLightsFailed)
                end
            end)
            if rx:loadFromXML(linkNode, string.gsub(file.path, getAppBasePath(), ""), "") then
                local rz, wy, wz = localToWorld(linkNode, 0, 0, -0.2)
                local rx, ry, rz = localRotationToWorld(linkNode, -1.5707963267948966, 0, 0)
                g_debugManager:addElement(DebugText3D.new():createWithWorldPos(rz, wy, wz, rx, ry, rz, file.filename, 0.07), nil, nil, math.huge)
                g_debugManager:addElement(DebugGizmo.new():createWithNode(linkNode, "", nil, nil, 0.1), nil, nil, math.huge)
                value = basePath
                bitIndex = basePath
            else
                value = basePath
                bitIndex = basePath
            end
        end
    end
    BeaconLight.spawnDebugBeacons(SharedLight.debugRootNode)
end
